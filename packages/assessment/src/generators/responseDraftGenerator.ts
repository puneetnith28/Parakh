import { RequirementAssessment } from "@parakh/contracts";

export interface GroundedProposalDraft {
  disclaimer: string;
  opening: string;
  demonstratedCapabilities: {
    requirementText: string;
    evidenceProof: string;
  }[];
  collaborationTopics: {
    requirementText: string;
    inquiry: string;
  }[];
  closing: string;
  fullDraftText: string;
}

/**
 * Generates an honest, grounded proposal/response draft that only claims verified skills
 * and clearly distinguishes working evidence from areas requiring client discussion.
 */
export function generateProposalDraft(
  assessments: RequirementAssessment[],
  repositoryUrl: string,
  opportunityTitle: string = "your technical project"
): GroundedProposalDraft {
  const disclaimer =
    "[ADVISORY DISCLAIMER: This draft was generated by Parakh from verified codebase evidence. Review and customize all technical claims prior to sending.]";

  const opening = `Hello,

Thank you for considering our profile for ${opportunityTitle}. We reviewed your requirements in detail and compared them directly against verified production code in our reference repository (${repositoryUrl}).`;

  // 1. Collect only strictly demonstrated or manually verified requirements
  const demonstratedItems = assessments.filter((a) => a.status === "demonstrated");
  const demonstratedCapabilities = demonstratedItems.map((item) => {
    const proofFile =
      item.citations && item.citations.length > 0
        ? ` (verified in ${item.citations[0].path.split("/").pop()})`
        : "";
    return {
      requirementText: item.requirementText,
      evidenceProof: `${item.rationale}${proofFile}`,
    };
  });

  // 2. Collect partial or unverified requirements as discussion topics (never affirmed)
  const gapItems = assessments.filter(
    (a) => a.status === "partially_demonstrated" || a.status === "not_demonstrated" || a.status === "needs_review"
  );

  const collaborationTopics = gapItems.map((item) => {
    let inquiry = "";
    if (item.status === "partially_demonstrated") {
      inquiry = `We have baseline architecture in place (${item.rationale}). We would love to discuss your specific production scale and test criteria.`;
    } else if (item.status === "needs_review") {
      inquiry = `We would appreciate reviewing your preferred technical standards for this item to ensure full alignment.`;
    } else {
      inquiry = `We have not directly addressed this in the reference repo and look forward to detailing our approach or linking relevant supplemental work.`;
    }

    return {
      requirementText: item.requirementText,
      inquiry,
    };
  });

  // Build full text
  const sections: string[] = [disclaimer, "", opening, ""];

  if (demonstratedCapabilities.length > 0) {
    sections.push("### Verified Capabilities directly applicable to your brief:");
    demonstratedCapabilities.forEach((cap, i) => {
      sections.push(`${i + 1}. **${cap.requirementText}**`);
      sections.push(`   Evidence: ${cap.evidenceProof}`);
    });
    sections.push("");
  }

  if (collaborationTopics.length > 0) {
    sections.push("### Areas to Align & Discuss in our kickoff:");
    collaborationTopics.forEach((topic, i) => {
      sections.push(`${i + 1}. **${topic.requirementText}**`);
      sections.push(`   ${topic.inquiry}`);
    });
    sections.push("");
  }

  const closing = `We believe in verifiable engineering and transparent communication from day one. When would be a good time for a brief call to discuss next steps?

Best regards,`;

  sections.push(closing);

  return {
    disclaimer,
    opening,
    demonstratedCapabilities,
    collaborationTopics,
    closing,
    fullDraftText: sections.join("\n"),
  };
}
