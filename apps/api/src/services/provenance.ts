import crypto from "node:crypto";
import { type AssessmentReport } from "@parakh/contracts";
import { runManager } from "./runManager.js";
import { config } from "../config.js";

/**
 * Report Provenance & Tamper-Proof Verification Service
 *
 * Ensures that assessment reports cannot be fabricated or directly injected by
 * untrusted clients. Every report must originate from a verified server analysis run.
 */

// Stable server secret for HMAC signing (fallback to deterministic runtime secret)
const SERVER_PROVENANCE_SECRET =
  process.env.PROVENANCE_SECRET ||
  config.MODEL_API_KEY ||
  config.AI_STUDIO_API_KEY ||
  "parakh-provenance-secret-key-v1";

export interface ProvenancePayload {
  runId: string;
  reportId: string;
  opportunityId: string;
  repositoryUrl: string;
  resolvedCommitSha: string;
}

/**
 * Generates an HMAC-SHA256 cryptographic signature proving that a report
 * was generated by the trusted server analysis workflow.
 */
export function issueProvenanceToken(payload: ProvenancePayload): string {
  const data = `${payload.runId}:${payload.reportId}:${payload.opportunityId}:${payload.repositoryUrl.toLowerCase()}:${payload.resolvedCommitSha.toLowerCase()}`;
  return crypto.createHmac("sha256", SERVER_PROVENANCE_SECRET).update(data).digest("hex");
}

/**
 * Validates the cryptographic provenance of an assessment report.
 * Requires:
 * 1. A valid, non-empty provenance token.
 * 2. Token matches the HMAC-SHA256 signature for the report's identity and commit SHA.
 * 3. An associated server-side analysis run exists in RunManager.
 */
export function verifyReportProvenance(
  report: AssessmentReport,
  runId: string,
  token: string
): { verified: boolean; reason?: string } {
  if (!runId || typeof runId !== "string" || !runId.trim()) {
    return { verified: false, reason: "Missing or invalid server analysis run identifier (runId)." };
  }

  if (!token || typeof token !== "string" || token.length !== 64) {
    return { verified: false, reason: "Missing or invalid 256-bit provenance token." };
  }

  // 1. Verify cryptographic HMAC signature
  const expectedToken = issueProvenanceToken({
    runId,
    reportId: report.id,
    opportunityId: report.opportunityId,
    repositoryUrl: report.repositoryUrl,
    resolvedCommitSha: report.resolvedCommitSha,
  });

  const tokenBuffer = Buffer.from(token, "hex");
  const expectedBuffer = Buffer.from(expectedToken, "hex");

  if (
    tokenBuffer.length !== expectedBuffer.length ||
    !crypto.timingSafeEqual(tokenBuffer, expectedBuffer)
  ) {
    return {
      verified: false,
      reason: "Cryptographic provenance signature mismatch. Report was not generated by this server.",
    };
  }

  // 2. Verify that runId was registered in the server's RunManager
  const recordedRun = runManager.getRun(runId);
  if (!recordedRun) {
    return {
      verified: false,
      reason: `No active or completed server analysis run found for runId '${runId}'.`,
    };
  }

  return { verified: true };
}
