import crypto from "node:crypto";
import { type AssessmentReport } from "@parakh/contracts";
import { runManager } from "./runManager.js";
import { config } from "../config.js";

/**
 * Report Provenance & Tamper-Proof Verification Service
 *
 * Ensures that assessment reports cannot be fabricated or directly injected by
 * untrusted clients. Every report must originate from a verified server analysis run.
 */

// Stable server secret for HMAC signing (fallback to deterministic runtime secret)
const SERVER_PROVENANCE_SECRET =
  process.env.PROVENANCE_SECRET ||
  config.MODEL_API_KEY ||
  config.AI_STUDIO_API_KEY ||
  "parakh-provenance-secret-key-v1";

export interface ProvenancePayload {
  runId: string;
  reportId: string;
  opportunityId: string;
  repositoryUrl: string;
  resolvedCommitSha: string;
  contentHash?: string;
  report?: AssessmentReport;
}

/**
 * Deterministically computes a SHA-256 hash of all material report content:
 * - Status, assessments (statuses, rationales, citations, next actions),
 * - Coverage summary counts, limitations, and gap recommendations.
 * Any client modification to these fields changes this hash and invalidates provenance.
 */
export function computeReportContentHash(report: AssessmentReport): string {
  const normalizedAssessments = (report.assessments || [])
    .slice()
    .sort((a, b) => a.requirementId.localeCompare(b.requirementId))
    .map((a) => {
      const normalizedCitations = (a.citations || [])
        .slice()
        .sort((c1, c2) => {
          const key1 = `${c1.candidateId}:${c1.path}:${c1.startLine ?? 0}`;
          const key2 = `${c2.candidateId}:${c2.path}:${c2.startLine ?? 0}`;
          return key1.localeCompare(key2);
        })
        .map((c) => ({
          candidateId: c.candidateId,
          repository: (c.repository || "").toLowerCase(),
          commitSha: (c.commitSha || "").toLowerCase(),
          path: c.path,
          canonicalUrl: c.canonicalUrl,
          startLine: c.startLine ?? null,
          endLine: c.endLine ?? null,
          snippet: c.snippet,
          supports: c.supports ?? null,
          limitations: c.limitations ?? null,
        }));

      const citedCandidateIds = (a.citedCandidateIds || []).slice().sort();
      const nextActions = (Array.isArray(a.nextActions) ? a.nextActions : [a.nextActions].filter(Boolean))
        .map(String)
        .slice()
        .sort();

      return {
        requirementId: a.requirementId,
        requirementText: a.requirementText,
        status: a.status,
        rationale: a.rationale,
        confidence: a.confidence,
        citedCandidateIds,
        citations: normalizedCitations,
        limitations: a.limitations ?? null,
        nextActions,
        originalStatus: a.originalStatus ?? null,
        downgradeReason: a.downgradeReason ?? null,
      };
    });

  const canonicalObj = {
    id: report.id,
    opportunityId: report.opportunityId,
    repositoryUrl: (report.repositoryUrl || "").toLowerCase(),
    resolvedCommitSha: (report.resolvedCommitSha || "").toLowerCase(),
    status: report.status,
    scannedFilesCount: report.scannedFilesCount ?? 0,
    skippedFilesCount: report.skippedFilesCount ?? 0,
    assessments: normalizedAssessments,
    coverageSummary: {
      total: report.coverageSummary?.total ?? 0,
      demonstrated: report.coverageSummary?.demonstrated ?? 0,
      partiallyDemonstrated: report.coverageSummary?.partiallyDemonstrated ?? 0,
      notDemonstrated: report.coverageSummary?.notDemonstrated ?? 0,
      needsReview: report.coverageSummary?.needsReview ?? 0,
    },
    limitations: (report.limitations || []).slice().sort(),
    gapRecommendations: (report.gapRecommendations || []).slice().sort(),
  };

  const serialized = JSON.stringify(canonicalObj);
  return crypto.createHash("sha256").update(serialized).digest("hex");
}

/**
 * Generates an HMAC-SHA256 cryptographic signature proving that a report
 * was generated by the trusted server analysis workflow and has not been tampered with.
 */
export function issueProvenanceToken(payload: ProvenancePayload): string {
  const contentHash =
    payload.contentHash ||
    (payload.report ? computeReportContentHash(payload.report) : "") ||
    (payload.runId ? runManager.getRun(payload.runId)?.reportContentHash : "") ||
    "";

  const data = `${payload.runId}:${payload.reportId}:${payload.opportunityId}:${payload.repositoryUrl.toLowerCase()}:${payload.resolvedCommitSha.toLowerCase()}:${contentHash}`;
  return crypto.createHmac("sha256", SERVER_PROVENANCE_SECRET).update(data).digest("hex");
}

/**
 * Validates the cryptographic provenance of an assessment report.
 * Requires:
 * 1. A valid, non-empty 256-bit hexadecimal provenance token.
 * 2. An associated server-side analysis run exists in RunManager matching the report identity.
 * 3. Exact match against authoritative server-recorded report content hash (if present).
 * 4. Token matches the HMAC-SHA256 signature binding identity and material report content.
 */
export function verifyReportProvenance(
  report: AssessmentReport,
  runId: string,
  token: string
): { verified: boolean; reason?: string } {
  if (!runId || typeof runId !== "string" || !runId.trim()) {
    return { verified: false, reason: "Missing or invalid server analysis run identifier (runId)." };
  }

  if (!token || typeof token !== "string" || !/^[0-9a-f]{64}$/i.test(token.trim())) {
    return { verified: false, reason: "Missing or invalid 256-bit provenance token." };
  }

  // 1. Verify that runId was registered in the server's RunManager
  const recordedRun = runManager.getRun(runId);
  if (!recordedRun) {
    return {
      verified: false,
      reason: `No active or completed server analysis run found for runId '${runId}'.`,
    };
  }

  // 2. Cross-report / cross-run isolation checks
  if (recordedRun.reportId && recordedRun.reportId !== report.id) {
    return {
      verified: false,
      reason: `Report ID mismatch: run '${runId}' generated report '${recordedRun.reportId}', but received '${report.id}'.`,
    };
  }

  if (recordedRun.opportunityId && recordedRun.opportunityId !== report.opportunityId) {
    return {
      verified: false,
      reason: "Opportunity ID mismatch with server analysis run record.",
    };
  }

  if (
    recordedRun.repositoryUrl &&
    recordedRun.repositoryUrl.toLowerCase() !== report.repositoryUrl.toLowerCase()
  ) {
    return {
      verified: false,
      reason: "Repository URL mismatch with server analysis run record.",
    };
  }

  // 3. Compute canonical content hash of the submitted report
  const contentHash = computeReportContentHash(report);

  // If server run recorded authoritative reportContentHash, verify exact match
  if (
    recordedRun.reportContentHash &&
    recordedRun.reportContentHash !== contentHash
  ) {
    return {
      verified: false,
      reason: "Report content does not match the authoritative server analysis run (material content altered).",
    };
  }

  // 4. Verify cryptographic HMAC signature binding full content
  const expectedToken = issueProvenanceToken({
    runId,
    reportId: report.id,
    opportunityId: report.opportunityId,
    repositoryUrl: report.repositoryUrl,
    resolvedCommitSha: report.resolvedCommitSha,
    contentHash,
  });

  const tokenBuffer = Buffer.from(token.toLowerCase(), "hex");
  const expectedBuffer = Buffer.from(expectedToken.toLowerCase(), "hex");

  if (
    tokenBuffer.length !== expectedBuffer.length ||
    !crypto.timingSafeEqual(tokenBuffer, expectedBuffer)
  ) {
    return {
      verified: false,
      reason: "Cryptographic provenance signature mismatch. Report was not generated by this server or content has been tampered with.",
    };
  }

  return { verified: true };
}
